import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const read=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const html=read('../augustsignature/index.html'),css=read('../augustsignature/signature-display.css');
const studio=read('../augustsignature/studio.js'),redraw=read('../functions/api/augustsignature/redraw.js');
assert.match(html,/id="signature-black-on-white" color-interpolation-filters="sRGB"/);
assert.match(html,/<feColorMatrix type="saturate" values="0"/);
assert.equal((html.match(/type="discrete" tableValues="0 1"/g)||[]).length,3,'all RGB channels use the same binary ink/paper treatment');
assert.match(html,/<feFlood flood-color="#ffffff" result="paper"/,'transparent samples also receive white paper');
assert.match(html,/signature-display\.css\?v=black-on-white-1/);
for(const selector of ['.people-art img','.people-art svg>image','.signature-art>image','.custom-signature'])assert.ok(css.includes(selector),selector);
assert.match(css,/filter:url\(#signature-black-on-white\)/);
assert.match(css,/stroke:#000000;background-color:#ffffff/);
assert.match(css,/Focus boxes, start markers and faint tracing overlays are teaching UI/);
assert.match(studio,/Display normalized to black ink on white/);
assert.doesNotMatch(studio,/CC BY-SA[^\n]*· unchanged/,'display adaptations must not be labeled unchanged');
for(const phrase of ['WHITE (#FFFFFF)','BLACK (#000000)','cannot be overridden by feedback','No blue, gray, cream, colored or photographic paper'])assert.ok(redraw.includes(phrase),phrase);
const catalog=read('../augustsignature/autographs.js');
assert.match(catalog,/DAMON_ALBARN_PAGE/,'the sourced autograph is preserved, not generatively replaced');
assert.match(catalog,/source:'https:\/\/eil\.com\//);
const context=vm.createContext({window:{},artSerial:0});
vm.runInContext(catalog,context);
const from=studio.indexOf('  function autographImage(p)'),to=studio.indexOf('  function renderPeople()',from);
assert.ok(from>0&&to>from);vm.runInContext(studio.slice(from,to),context);
const damon=context.window.augustAutographs.find(p=>p.id==='damon');
const markup=context.autographImage(damon);
assert.match(markup,/<clipPath/,'a viewBox alone must not let the photo bleed into letterboxed margins');
assert.match(markup,/<rect x="55" y="60" width="415" height="365"/);
assert.match(markup,/clip-path="url\(#autograph-crop-/);
console.log('PASS: black/white rendering covers cropped autographs, regular samples, originals and revisions; pure-white compositing; vector ink; redraw rules; provenance disclosure.');
